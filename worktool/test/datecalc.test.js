/* ============================================================
   纯逻辑用例：node test/datecalc.test.js
   全部离线。日期计算最容易错的就是月末、跨年、夏令时这三处，
   所以这里刻意把边界都钉死。
   ============================================================ */
'use strict';

var D = require('../js/lib/datecalc.js');

var pass = 0, fail = 0;
function check(name, got, want) {
  var ok = got === want;
  ok ? pass++ : fail++;
  console.log((ok ? '  ok   ' : '  FAIL ') + name);
  if (!ok) console.log('         期望: ' + want + '\n         实际: ' + got);
}
function d(s) { return D.parseYmd(s); }
function y(n) { return D.ymd(n); }

/* ---------- 解析与格式化 ---------- */
console.log('\n── 解析与格式化 ──');
check('解析标准写法', y(d('2026-10-14')), '2026-10-14');
check('容忍不补零', y(d('2026-1-5')), '2026-01-05');
check('容忍首尾空格', y(d('  2026-10-14  ')), '2026-10-14');
check('空串返回 null', d(''), null);
check('乱写返回 null', d('not a date'), null);
check('2 月 30 日不存在（不能被自动进位）', d('2026-02-30'), null);
check('13 月不存在', d('2026-13-01'), null);
check('闰年的 2 月 29 日合法', y(d('2024-02-29')), '2024-02-29');
check('平年的 2 月 29 日不合法', d('2026-02-29'), null);
check('星期计算正确', D.weekCN(d('2026-10-14')), '星期三');
check('格式化写法', D.fmt(d('2026-10-14')), '2026-10-14 星期三');

/* ---------- 加减：天 / 周 ---------- */
console.log('\n── 加减天数 ──');
check('加 1 天', y(D.add(d('2026-10-14'), 1, 'day')), '2026-10-15');
check('减 1 天', y(D.add(d('2026-10-14'), -1, 'day')), '2026-10-13');
check('跨月：10-31 + 1 天', y(D.add(d('2026-10-31'), 1, 'day')), '2026-11-01');
check('跨年：12-31 + 1 天', y(D.add(d('2026-12-31'), 1, 'day')), '2027-01-01');
check('加 2 周', y(D.add(d('2026-10-14'), 2, 'week')), '2026-10-28');
check('减 3 周', y(D.add(d('2026-10-14'), -3, 'week')), '2026-09-23');
check('加 0 天不变', y(D.add(d('2026-10-14'), 0, 'day')), '2026-10-14');
check('未知单位按天处理', y(D.add(d('2026-10-14'), 2, 'nonsense')), '2026-10-16');
check('非法数字原样返回', y(D.add(d('2026-10-14'), NaN, 'day')), '2026-10-14');

/* ---------- 加减：月 / 年（月末是重点） ---------- */
console.log('\n── 加减月 / 年 ──');
check('1-31 加 1 月 → 平年 2-28', y(D.add(d('2026-01-31'), 1, 'month')), '2026-02-28');
check('1-31 加 1 月 → 闰年 2-29', y(D.add(d('2024-01-31'), 1, 'month')), '2024-02-29');
check('3-31 减 1 月 → 2-28', y(D.add(d('2026-03-31'), -1, 'month')), '2026-02-28');
check('5-31 加 1 月 → 6-30', y(D.add(d('2026-05-31'), 1, 'month')), '2026-06-30');
check('常规加月', y(D.add(d('2026-10-14'), 3, 'month')), '2027-01-14');
check('跨年减月', y(D.add(d('2026-02-14'), -3, 'month')), '2025-11-14');
check('加 12 个月 = 加 1 年', y(D.add(d('2026-10-14'), 12, 'month')), '2027-10-14');
check('加 1 年', y(D.add(d('2026-10-14'), 1, 'year')), '2027-10-14');
check('2-29 加 1 年 → 平年 2-28', y(D.add(d('2024-02-29'), 1, 'year')), '2025-02-28');
check('2-29 加 4 年 → 闰年 2-29', y(D.add(d('2024-02-29'), 4, 'year')), '2028-02-29');
check('减 2 年', y(D.add(d('2026-10-14'), -2, 'year')), '2024-10-14');

/* ---------- 天数差 ---------- */
console.log('\n── 天数差 ──');
check('同一天为 0', D.diffDays(d('2026-10-14'), d('2026-10-14')), 0);
check('相邻一天为 1', D.diffDays(d('2026-10-14'), d('2026-10-15')), 1);
check('反向为负', D.diffDays(d('2026-10-15'), d('2026-10-14')), -1);
check('跨月', D.diffDays(d('2026-10-31'), d('2026-11-01')), 1);
check('跨年', D.diffDays(d('2026-12-31'), d('2027-01-01')), 1);
check('整年（平年）', D.diffDays(d('2025-01-01'), d('2026-01-01')), 365);
check('整年（含闰日）', D.diffDays(d('2024-01-01'), d('2025-01-01')), 366);
check('闰日相邻', D.diffDays(d('2024-02-28'), d('2024-03-01')), 2);
check('平年 2 月末相邻', D.diffDays(d('2026-02-28'), d('2026-03-01')), 1);
check('一个季度', D.diffDays(d('2026-01-01'), d('2026-04-01')), 90);

/* ---------- 折合年月日 ---------- */
console.log('\n── 折合年月日 ──');
var r1 = D.diffYmd(d('2020-01-15'), d('2026-10-14'));
check('整段：6 年 8 个月 29 天', r1.years + '/' + r1.months + '/' + r1.days, '6/8/29');
check('总计天数与 diffDays 一致', r1.total, D.diffDays(d('2020-01-15'), d('2026-10-14')));
check('未交换顺序', r1.swapped, false);
var r2 = D.diffYmd(d('2026-10-14'), d('2026-10-14'));
check('同日全为 0', r2.years + '/' + r2.months + '/' + r2.days, '0/0/0');
var r3 = D.diffYmd(d('2026-10-14'), d('2025-01-01'));
check('反向输入被交换并标记', r3.swapped, true);
check('反向也返回正数', r3.years >= 0 && r3.months >= 0 && r3.days >= 0, true);
check('反向的 total 取绝对值', r3.total, Math.abs(D.diffDays(d('2026-10-14'), d('2025-01-01'))));
var r4 = D.diffYmd(d('2026-01-31'), d('2026-03-01'));
check('跨月末折合：1 个月零 1 天', r4.months + '/' + r4.days, '1/1');

/* ---------- 边界与工具函数 ---------- */
console.log('\n── 边界 ──');
check('归一化丢掉时分秒', D.ymd(D.norm(new Date(2026, 9, 14, 23, 59, 59))), '2026-10-14');
check('clampDay 平年 2 月夹到 28', D.clampDay(2026, 1, 31), 28);
check('clampDay 闰年 2 月夹到 29', D.clampDay(2024, 1, 31), 29);
check('clampDay 正常月不动', D.clampDay(2026, 9, 14), 14);
check('全是本地时间，不涉 UTC', D.ymd(new Date(2026, 0, 1)), '2026-01-01');

console.log('\n' + '='.repeat(46));
console.log('结果: ' + pass + ' 通过 / ' + fail + ' 失败');
if (fail) process.exit(1);
